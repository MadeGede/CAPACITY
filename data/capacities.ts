export function getCapacity(id: string): Capacity | undefined {
  return capacities.find((capacity) => capacity.id === id);
}

// Editorial category groupings for browsing related demo profiles, not demand matching.
const relatedCategories: Record<Category, readonly Category[]> = {
  "CNC & Machining": ["3D Printing", "Assembly"],
  "Plastic Manufacturing": ["Packaging", "3D Printing"],
  Packaging: ["Printing", "Plastic Manufacturing"],
  "Food Production": ["Packaging", "Warehousing"],
  Textile: ["Printing", "Assembly"],
  Printing: ["Packaging", "Textile"],
  "3D Printing": ["CNC & Machining", "Plastic Manufacturing"],
  Assembly: ["CNC & Machining", "Plastic Manufacturing"],
  Warehousing: ["Packaging", "Assembly"],
};

export function getSimilarCapacities(provider: Capacity, count = 3, providers: readonly Capacity[] = capacities): Capacity[] {
  const categoryOrder: readonly Category[] = [
    provider.category,
    ...relatedCategories[provider.category],
  ];

  return providers
    .filter((capacity) => capacity.id !== provider.id && categoryOrder.includes(capacity.category))
    .sort((a, b) =>
      categoryOrder.indexOf(a.category) - categoryOrder.indexOf(b.category) ||
      b.ranking - a.ranking,
    )
    .slice(0, Math.max(0, count));
}
